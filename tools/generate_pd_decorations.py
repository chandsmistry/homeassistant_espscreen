"""Frozen 24px decorations for native PD cards, not full-card pictures.

Noto Color Emoji is already installed in the add-on (Apache 2.0). Pass that font
with --font; the generated header records its hash. Roboto supplies the symbols.
"""
from pathlib import Path
import argparse,hashlib,sys
from PIL import Image,ImageDraw,ImageFont
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'screen_manager/app'))
import pd_cards
p=argparse.ArgumentParser();p.add_argument('--symbols',type=Path,required=True);p.add_argument('--font',type=Path,required=True);args=p.parse_args()
pd_cards.EMOJI_FONTS=(str(args.font),)
chars='⚙🔴⚡🎯🚀🔄💠⚖👑☀🌙🛡⏳🔒✅❌🟢🔋💤🏠🍃'
mono='→✓✗●○≣Σ䷡'
lines=['#pragma once','// Generated by tools/generate_pd_decorations.py; Noto Color Emoji, Roboto and DejaVu: licenses in fonts/pd-decorations-licenses.txt.',
 '// Noto SHA256: '+hashlib.sha256(args.font.read_bytes()).hexdigest(), '#include <cstdint>', 'namespace pd_decorations {',
 'inline constexpr int SIDE=24;', 'struct Asset { uint32_t codepoint; const uint8_t *pixels; bool ink; };']
entries=[]
for index,ch in enumerate(chars+mono):
 if ch in chars:
  im=pd_cards.emoji_image(ch)
  if im is None:raise SystemExit(f'No glyph for {ch}')
 elif ch=='䷡':
  im=Image.new('RGBA',(24,24));d=ImageDraw.Draw(im)
  for row in range(6):
   yy=2+row*3
   if row<2:
    d.rectangle((4,yy,10,yy+1),fill='white');d.rectangle((14,yy,20,yy+1),fill='white')
   else:d.rectangle((4,yy,20,yy+1),fill='white')
 else:
  face=ImageFont.truetype(str(pd_cards.FONT_DIR/'Roboto-400.ttf'),96)
  if ch in '≣✓✗':face=ImageFont.truetype(str(args.symbols),96)
  im=Image.new('RGBA',(128,128));ImageDraw.Draw(im).text((4,0),ch,font=face,fill='white');im=im.crop(im.getbbox())
 im.thumbnail((24,24),Image.Resampling.LANCZOS);out=Image.new('RGBA',(24,24));out.alpha_composite(im,((24-im.width)//2,(24-im.height)//2))
 data=out.tobytes('raw','BGRA');name=f'pixels_{index}'
 lines.append(f'inline constexpr uint8_t {name}[] = {{'+','.join(str(x) for x in data)+'};')
 entries.append(f'{{{ord(ch)}u,{name},{"true" if ch in mono else "false"}}}')
lines.extend(['inline constexpr Asset ASSETS[] = {'+','.join(entries)+'};','}  // namespace pd_decorations',''])
(ROOT/'components/smart_display/pd_decorations.h').write_text('\n'.join(lines))
print(f'{len(entries)} decorations, {len(entries)*24*24*4} bytes of pixels')
